    /** @return array{year: int, month: int, day: int} */
    public static function fromAd(DateTimeInterface $date): array
    {
        $reference = new DateTimeImmutable('1943-04-14', new DateTimeZone('UTC'));
        $target = new DateTimeImmutable($date->format('Y-m-d'), new DateTimeZone('UTC'));

        $days = (int) $reference->diff($target)->format('%r%a');

        if ($days < 0) {
            throw new InvalidArgumentException('AD date is before the supported BS range (starts 1943-04-14).');
        }

        $year = self::MIN_YEAR;

        while (true) {
            if ($year > self::MAX_YEAR) {
                throw new InvalidArgumentException('AD date is after the supported BS range (ends 2043-04-13).');
            }

            $yearDays = array_sum(self::MONTH_DAYS[$year - self::MIN_YEAR]);

            if ($days < $yearDays) {
                break;
            }

            $days -= $yearDays;
            $year++;
        }

        $month = 1;

        foreach (self::MONTH_DAYS[$year - self::MIN_YEAR] as $monthDays) {
            if ($days < $monthDays) {
                break;
            }

            $days -= $monthDays;
            $month++;
        }

        return ['year' => $year, 'month' => $month, 'day' => $days + 1];
    }

    public static function toAd(int $year, int $month, int $day): DateTimeImmutable
    {
        if ($year < self::MIN_YEAR || $year > self::MAX_YEAR) {
            throw new InvalidArgumentException("BS year must be between 2000 and 2099, got {$year}.");
        }

        if ($month < 1 || $month > 12) {
            throw new InvalidArgumentException("BS month must be between 1 and 12, got {$month}.");
        }

        $months = self::MONTH_DAYS[$year - self::MIN_YEAR];

        if ($day < 1 || $day > $months[$month - 1]) {
            throw new InvalidArgumentException("BS day must be between 1 and {$months[$month - 1]} for month {$month} of year {$year}.");
        }

        $offset = array_sum(array_slice($months, 0, $month - 1)) + $day - 1;

        for ($y = self::MIN_YEAR; $y < $year; $y++) {
            $offset += array_sum(self::MONTH_DAYS[$y - self::MIN_YEAR]);
        }

        return (new DateTimeImmutable('1943-04-14', new DateTimeZone('UTC')))->modify("+{$offset} days");
    }

    /** Tokens: Y (year), m (zero-padded month), n (month), d (zero-padded day), j (day), F (English month name). */
    public static function format(DateTimeInterface $date, string $format = 'Y-m-d'): string
    {
        $bs = self::fromAd($date);

        return strtr($format, [
            'Y' => (string) $bs['year'],
            'n' => (string) $bs['month'],
            'm' => str_pad((string) $bs['month'], 2, '0', STR_PAD_LEFT),
            'j' => (string) $bs['day'],
            'd' => str_pad((string) $bs['day'], 2, '0', STR_PAD_LEFT),
            'F' => self::MONTHS_EN[$bs['month'] - 1],
        ]);
    }
